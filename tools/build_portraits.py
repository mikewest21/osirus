#!/usr/bin/env python3
"""Embed the painted character portraits into apps-script/Index.html.

Source art: art/portraits/<ID>.png (transparent PNGs; ID = founder id, e.g. MOMO, or GHOST).
Each one is trimmed to the character, placed in a square with the feet on the bottom edge,
resized to SIZE px and stored as WebP (with alpha) in a data URI between the PORTRAITS markers.
Run from the repo root:  python3 tools/build_portraits.py
"""
import base64, glob, io, json, os, re
from PIL import Image

SIZE, QUALITY = 288, 82
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
html_path = os.path.join(ROOT, 'apps-script', 'Index.html')

def square_feet_down(im):
    im = im.convert('RGBA')
    box = im.getchannel('A').point(lambda a: 255 if a > 24 else 0).getbbox()
    im = im.crop(box)
    w, h = im.size
    side = max(w, h)
    canvas = Image.new('RGBA', (side, side), (0, 0, 0, 0))
    canvas.paste(im, ((side - w) // 2, side - h), im)   # centred, feet on the bottom edge
    return canvas.resize((SIZE, SIZE), Image.LANCZOS)

out = {}
for f in sorted(glob.glob(os.path.join(ROOT, 'art', 'portraits', '*.png'))):
    key = os.path.splitext(os.path.basename(f))[0]
    buf = io.BytesIO()
    square_feet_down(Image.open(f)).save(buf, 'WEBP', quality=QUALITY, method=6)
    out[key] = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()
    print('%-6s %5.1f KB' % (key, len(buf.getvalue()) / 1024))

html = open(html_path, encoding='utf-8').read()
block = '/* PORTRAITS:BEGIN (generated by tools/build_portraits.py) */\n  var PORTRAIT = ' + json.dumps(out, separators=(',', ':')) + ';\n  /* PORTRAITS:END */'
new, n = re.subn(r'/\* PORTRAITS:BEGIN.*?/\* PORTRAITS:END \*/', lambda m: block, html, flags=re.S)
if n != 1: raise SystemExit('PORTRAITS markers not found exactly once in Index.html')
open(html_path, 'w', encoding='utf-8').write(new)
print('embedded %d portraits, %.0f KB total' % (len(out), sum(len(v) for v in out.values()) / 1024))
